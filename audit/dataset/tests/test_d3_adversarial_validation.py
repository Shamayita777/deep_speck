"""
Controlled adversarial validation for Dataset Integrity Audit D3.

Scientific status
-----------------
NON-EVIDENTIARY.

This suite validates D3 against independently constructed controls and
predeclared distributional violations.

It complements test_d3_invariants.py.

It does NOT establish that the real Gohr dataset passes or fails D3.
The production result remains the result generated by:

    audit/dataset/experiments/d3_gohr_distribution_statistics.py

Threats tested here:

    - clean matched distribution;
    - class-ratio shift;
    - isolated first-order feature shift;
    - isolated second-order feature-pair shift.

All effects are deliberately strong enough that expected detection is
derived from the construction rather than tuned after observing D3 output.
"""

from __future__ import annotations

import numpy as np
import pytest

from audit.dataset import d3_distribution_statistics as d3


FAMILYWISE_ALPHA = 0.01


def _balanced_dataset(n: int = 200, d: int = 4) -> np.ndarray:
    """
    Deterministic balanced binary fixture.

    Each feature contains exactly n/2 ones.
    """
    if n % 2:
        raise ValueError("n must be even.")

    rows = np.zeros((n, d), dtype=np.uint8)

    for j in range(d):
        rows[: n // 2, j] = 1

    return rows


def _balanced_labels(n: int = 200) -> np.ndarray:
    if n % 2:
        raise ValueError("n must be even.")

    return np.concatenate(
        [
            np.zeros(n // 2, dtype=np.uint8),
            np.ones(n // 2, dtype=np.uint8),
        ]
    )


def _intended_distribution() -> dict[str, float]:
    return {
        "expected_class_ratio": 0.5,
        "expected_bit_probability": 0.5,
        "class_ratio_tolerance": 0.05,
        "bit_probability_tolerance": 0.05,
        "pairwise_tvd_tolerance": 0.01,
    }

def _independent_balanced_dataset() -> np.ndarray:
    """
    Deterministic balanced fixture.

    Every feature has P(X_i=1)=0.5.
    Features 0 and 1 are not identical, and their joint table
    contains all four combinations equally often.
    """
    rows = []

    for i in range(200):
        rows.append([
            (i // 1) % 2,
            (i // 2) % 2,
            (i // 4) % 2,
            (i // 8) % 2,
        ])

    return np.asarray(rows, dtype=np.uint8)

# ---------------------------------------------------------------------
# Clean null
# ---------------------------------------------------------------------

def test_clean_control_has_no_confirmed_d3_failure() -> None:
    """
    Known-null condition.

    Train/validation/test have identical empirical distributions.
    """
    x = _balanced_dataset()
    y = _balanced_labels()

    result = d3.audit_distribution(
        x,
        y,
        x.copy(),
        y.copy(),
        x.copy(),
        y.copy(),
        intended_distribution=_intended_distribution(),
        familywise_alpha=FAMILYWISE_ALPHA,
    )

    decision = d3.evaluate_decision(result)

    assert decision["outcome"] == "PASS"
    assert decision["counts"]["confirmed_failures"] == 0


# ---------------------------------------------------------------------
# Class-ratio fault
# ---------------------------------------------------------------------

def test_strong_class_imbalance_is_detected() -> None:
    """
    Reference:
        positive ratio = 0.50

    Fault:
        positive ratio = 0.85

    The effect is predeclared and far larger than the practical tolerance.
    """
    labels = np.concatenate(
        [
            np.zeros(30, dtype=np.uint8),
            np.ones(170, dtype=np.uint8),
        ]
    )

    observed = d3.class_distribution(labels)

    result = d3.class_balance_test(
        observed,
        expected_positive_ratio=0.5,
        practical_tolerance=0.05,
        alpha=0.01,
    )

    assert observed["positive_ratio"] == pytest.approx(0.85)
    assert result["absolute_difference"] == pytest.approx(0.35)

    assert result["practically_consistent"] is False
    assert result["statistically_inconsistent"] is True
    assert result["p_value"] < 1e-10


# ---------------------------------------------------------------------
# First-order marginal fault
# ---------------------------------------------------------------------

def test_isolated_first_order_feature_shift_is_detected() -> None:
    """
    Only feature 0 is changed.

    Reference:
        p(X_0 = 1) = 0.50

    Fault:
        p(X_0 = 1) = 0.90

    Other features remain exactly balanced.
    """
    reference = _balanced_dataset()

    shifted = reference.copy()
    shifted[:, 0] = 0
    shifted[:180, 0] = 1

    reference_summary = d3.summarize_partition(
        reference,
        _balanced_labels(),
    )

    shifted_summary = d3.summarize_partition(
        shifted,
        _balanced_labels(),
    )

    comparison = d3.compare_with_intended_distribution(
        shifted_summary,
        expected_class_ratio=0.5,
        expected_bit_probability=0.5,
        class_ratio_tolerance=0.05,
        bit_probability_tolerance=0.05,
        familywise_alpha=FAMILYWISE_ALPHA,
    )

    feature_records = comparison["binary_marginals"]["per_feature"]

    shifted_feature = feature_records[0]

    assert shifted_feature["absolute_difference"] == pytest.approx(0.40)
    assert comparison["binary_marginals"]["practically_consistent"] is False
    assert shifted_feature["statistically_inconsistent"] is True

    for record in feature_records[1:]:
        assert record["absolute_difference"] == pytest.approx(0.0)
        assert record["statistically_inconsistent"] is False

    # Explicitly confirm that the reference itself is still balanced.
    ref_probs = (
        reference_summary["binary_marginal_distribution"]
        ["per_feature_one_probability"]
    )

    assert all(p == pytest.approx(0.5) for p in ref_probs)


# ---------------------------------------------------------------------
# Second-order pairwise fault
# ---------------------------------------------------------------------

def test_isolated_pairwise_shift_is_detected() -> None:
    """
    Construct two datasets with the same individual marginals but a strong
    dependency change between features 0 and 1.

    Reference:
        independent/balanced construction.

    Fault:
        X_1 is made equal to X_0.

    Therefore:
        marginals remain approximately 0.5;
        joint distribution changes strongly.
    """
    reference = _independent_balanced_dataset()

    shifted = reference.copy()

    # Force feature 1 to equal feature 0.
    shifted[:, 1] = shifted[:, 0]

    result = d3.compare_pairwise_joint_distributions(
        reference,
        shifted,
        practical_tvd_tolerance=0.01,
        familywise_alpha=FAMILYWISE_ALPHA,
    )

    pair_records = {
        (record["feature_i"], record["feature_j"]): record
        for record in result["pair_summaries"]
    }

    target = pair_records[(0, 1)]

    assert target["tvd"] > 0.1
    assert target["statistically_inconsistent"] is True
    assert target["practically_inconsistent"] is True


# ---------------------------------------------------------------------
# Localisation check
# ---------------------------------------------------------------------

def test_first_order_fault_does_not_require_all_features_to_fail() -> None:
    """
    A localized fault should not be converted into a claim that every
    feature is abnormal.
    """
    reference = _balanced_dataset()
    shifted = reference.copy()

    shifted[:, 0] = 0
    shifted[:180, 0] = 1

    result = d3.compare_pairwise_joint_distributions(
        reference,
        shifted,
        practical_tvd_tolerance=0.01,
        familywise_alpha=FAMILYWISE_ALPHA,
    )

    # At least one pair involving the manipulated feature must show a
    # detectable distributional difference.
    affected = [
        record
        for record in result["pair_summaries"]
        if 0 in (record["feature_i"], record["feature_j"])
    ]

    assert affected

    assert any(
        record["statistically_inconsistent"]
        for record in affected
    )


# ---------------------------------------------------------------------
# Reproducibility of adversarial condition
# ---------------------------------------------------------------------

def test_adversarial_fixture_is_deterministic() -> None:
    """
    The fixture itself must be reproducible. This protects the validation
    experiment from accidentally acquiring hidden RNG dependence.
    """
    x1 = _balanced_dataset()
    x2 = _balanced_dataset()

    assert np.array_equal(x1, x2)

    shifted1 = x1.copy()
    shifted2 = x2.copy()

    shifted1[:, 1] = shifted1[:, 0]
    shifted2[:, 1] = shifted2[:, 0]

    assert np.array_equal(shifted1, shifted2)