# ---------------------------------------------------------------------
# Multiplicity fault
# ---------------------------------------------------------------------

def test_multiple_exact_copies_report_expected_multiplicity() -> None:
    """
    Controlled fault:

        create a representation with known multiplicity.

    The expected multiplicity is derived directly from fixture construction,
    not from the implementation under test.
    """
    partitions = fx.clean_partitions()

    train = partitions["train"].copy()

    # Construct a representation appearing three times.
    repeated = train[0].copy()
    train[1] = repeated
    train[2] = repeated

    result = d1.audit_duplicates(
        train=train,
        validation=partitions["validation"],
        test=partitions["test"],
        representation_convention="D1 adversarial validation fixture",
        feature_encoding="synthetic exact fixture",
    )

    train_stats = result["partitions"]["train"]

    assert train_stats["duplicate_groups"] == 1

    # Three occurrences imply two duplicate samples under D1's
    # documented k-1 multiplicity convention.
    assert train_stats["duplicate_samples"] == 2
    assert train_stats["maximum_multiplicity"] == 3

    decision = d1.evaluate_d1(result)

    assert decision["outcome"] == "FAIL"


# ---------------------------------------------------------------------
# Boundary: no false detection from row reordering
# ---------------------------------------------------------------------

def test_row_reordering_does_not_create_d1_violation() -> None:
    """
    Control:

        reorder rows without changing representations.

    Reordering alone must not create duplicates or cross-partition overlap.
    """
    partitions = fx.clean_partitions()

    train = partitions["train"][::-1].copy()
    validation = partitions["validation"][::-1].copy()
    test = partitions["test"][::-1].copy()

    result = d1.audit_duplicates(
        train=train,
        validation=validation,
        test=test,
        representation_convention="D1 adversarial validation fixture",
        feature_encoding="synthetic exact fixture",
    )

    for name in ("train", "validation", "test"):
        assert result["partitions"][name]["duplicate_samples"] == 0

    assert result["partition_overlap"]["train_validation"] == 0
    assert result["partition_overlap"]["train_test"] == 0
    assert result["partition_overlap"]["validation_test"] == 0

    assert d1.evaluate_d1(result)["outcome"] == "PASS"