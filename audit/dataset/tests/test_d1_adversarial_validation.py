# ---------------------------------------------------------------------
# Known-clean control
# ---------------------------------------------------------------------

def test_known_clean_control_has_no_d1_violation() -> None:
    """
    Predeclared null condition.

    Expected:
        - zero internal duplicates;
        - zero cross-partition overlap;
        - PASS.
    """
    partitions = fx.clean_partitions()

    result = d1.audit_duplicates(
        train=partitions["train"],
        validation=partitions["validation"],
        test=partitions["test"],
        representation_convention="D1 adversarial validation fixture",
        feature_encoding="synthetic exact fixture",
    )

    assert result["schema"]["valid"] is True

    for name in ("train", "validation", "test"):
        stats = result["partitions"][name]

        assert stats["duplicate_groups"] == 0
        assert stats["duplicate_samples"] == 0
        assert stats["unique_samples"] == stats["total_samples"]

    assert result["partition_overlap"]["train_validation"] == 0
    assert result["partition_overlap"]["train_test"] == 0
    assert result["partition_overlap"]["validation_test"] == 0

    decision = d1.evaluate_d1(result)

    assert decision["outcome"] == "PASS"


# ---------------------------------------------------------------------
# Exact within-partition duplicate fault
# ---------------------------------------------------------------------

@pytest.mark.parametrize(
    "factory,partition_name",
    [
        (fx.train_with_internal_duplicate, "train"),
        (fx.validation_with_internal_duplicate, "validation"),
        (fx.test_with_internal_duplicate, "test"),
    ],
    ids=[
        "train_internal_duplicate",
        "validation_internal_duplicate",
        "test_internal_duplicate",
    ],
)
def test_exact_internal_duplicate_is_detected(
    factory,
    partition_name: str,
) -> None:
    """
    Controlled fault:

        exactly one existing sample is repeated inside one partition.

    Expected:

        duplicate_samples == 1
        duplicate_groups == 1
        only the manipulated partition is affected
        D1 outcome == FAIL
    """
    partitions = factory()

    result = d1.audit_duplicates(
        train=partitions["train"],
        validation=partitions["validation"],
        test=partitions["test"],
        representation_convention="D1 adversarial validation fixture",
        feature_encoding="synthetic exact fixture",
    )

    stats = result["partitions"][partition_name]

    assert stats["duplicate_groups"] == 1
    assert stats["duplicate_samples"] == 1

    for name in ("train", "validation", "test"):
        if name != partition_name:
            assert result["partitions"][name]["duplicate_samples"] == 0

    assert result["partition_overlap"]["train_validation"] == 0
    assert result["partition_overlap"]["train_test"] == 0
    assert result["partition_overlap"]["validation_test"] == 0

    decision = d1.evaluate_d1(result)

    assert decision["outcome"] == "FAIL"


