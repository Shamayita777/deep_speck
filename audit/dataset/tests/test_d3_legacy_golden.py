"""
Golden regression: the legacy D3 path is the c603522 implementation.

The historical Gohr driver reaches the engine only through
audit_distribution() -> compare_partitions() / compare_pairwise_joint_distributions()
and evaluate_decision(). Leaving the driver file unchanged does not preserve
its behaviour if those functions change, so this suite pins their COMPLETE
output (every value, every key, the decision) on fixed inputs to output
produced by the c603522 engine itself:

    fixtures/d3_legacy_golden_c603522.json
        generated by loading `git show c603522:audit/dataset/d3_distribution_statistics.py`
        and running it on tests/d3_legacy_golden_cases.py

Cases include an empty-category (constant-feature) case and sparse tables,
the inputs on which the earlier, reverted engine change altered df and
p-values. Equality is exact after a JSON round trip (the representation in
which certificates are stored).

The live checks re-run the c603522 source from git; they are skipped, and
reported as skipped, when git or the commit is unavailable.
"""
from __future__ import annotations

import ast
import hashlib
import importlib.util
import json
import subprocess
from pathlib import Path

import pytest

from audit.dataset import d3_distribution_statistics as d3
from audit.dataset.tests.d3_legacy_golden_cases import (
    LEGACY_COMMIT, LEGACY_PATH, audit_cases, pair_cases)

FIXTURE = Path(__file__).parent / "fixtures" / "d3_legacy_golden_c603522.json"


def _roundtrip(obj):
    return json.loads(json.dumps(obj, sort_keys=True))


@pytest.fixture(scope="module")
def golden():
    return json.loads(FIXTURE.read_text())


@pytest.mark.parametrize("name", sorted(audit_cases()))
def test_legacy_audit_and_decision_match_c603522_exactly(golden, name) -> None:
    parts, intended, alpha = audit_cases()[name]
    args = [a for xy in parts for a in xy]
    r = d3.audit_distribution(*args, intended_distribution=intended, familywise_alpha=alpha)
    assert _roundtrip(r) == golden["audit"][name]["results"]
    assert _roundtrip(d3.evaluate_decision(r)) == golden["audit"][name]["decision"]


@pytest.mark.parametrize("name", sorted(pair_cases()))
def test_legacy_pair_comparison_matches_c603522_exactly(golden, name) -> None:
    a, b = pair_cases()[name]
    r = d3.compare_pairwise_joint_distributions(a, b, practical_tvd_tolerance=0.2, familywise_alpha=0.05)
    assert _roundtrip(r) == golden["pairs"][name]


def test_golden_covers_empty_category_and_sparse_tables(golden) -> None:
    """The fixture is not vacuous: it contains tables with an empty column,
    tables below Cochran's rule, and more than one legacy outcome."""
    recs = [rec for case in golden["audit"].values()
            for comp in case["results"]["partition_comparisons"].values()
            for rec in comp["second_order_feature_pairs"]["pair_summaries"]]
    assert any(min(x + y for x, y in zip(r["joint_a"], r["joint_b"])) == 0 for r in recs)
    assert all(r["degrees_of_freedom"] == 3 for r in recs)
    outcomes = {c["decision"]["outcome"] for c in golden["audit"].values()}
    assert {"FAIL", "INCONCLUSIVE"} <= outcomes


def test_confirmatory_path_is_separate_and_uses_observed_df() -> None:
    """Same constant-feature input: the legacy record keeps df = 3 while the
    confirmatory homogeneity test reports the observed df."""
    a, b = pair_cases()["zero_columns"]
    legacy = d3.compare_pairwise_joint_distributions(a, b, practical_tvd_tolerance=0.2,
                                                     familywise_alpha=0.05)["pair_summaries"]
    assert {r["degrees_of_freedom"] for r in legacy} == {3}
    table = d3._pair_cell_counts(a), d3._pair_cell_counts(b)
    conf = d3.homogeneity_test_batch(table[0], table[1], per_hypothesis_alpha=0.05, mc_seed=0)
    assert sorted(set(conf["degrees_of_freedom"].tolist())) == [0, 1]


def _git_head_source() -> str:
    try:
        out = subprocess.run(["git", "show", f"{LEGACY_COMMIT}:{LEGACY_PATH}"], capture_output=True,
                             text=True, timeout=30, cwd=Path(__file__).resolve().parents[3])
    except (OSError, subprocess.SubprocessError):
        pytest.skip("git unavailable")
    if out.returncode != 0:
        pytest.skip(f"commit {LEGACY_COMMIT} unavailable")
    return out.stdout


def test_fixture_was_generated_from_the_c603522_source(golden) -> None:
    src = _git_head_source()
    assert golden["legacy_source_sha256"] == hashlib.sha256(src.encode()).hexdigest()


def test_live_c603522_engine_still_agrees(tmp_path) -> None:
    src = _git_head_source()
    path = tmp_path / "d3_c603522.py"
    path.write_text(src)
    spec = importlib.util.spec_from_file_location("d3_c603522", path)
    old = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(old)
    for name, (parts, intended, alpha) in audit_cases().items():
        args = [a for xy in parts for a in xy]
        ro = old.audit_distribution(*args, intended_distribution=intended, familywise_alpha=alpha)
        rn = d3.audit_distribution(*args, intended_distribution=intended, familywise_alpha=alpha)
        assert _roundtrip(rn) == _roundtrip(ro), name


def test_every_legacy_definition_is_unchanged_apart_from_docstrings() -> None:
    def defs(text):
        out = {}
        for n in ast.parse(text).body:
            if isinstance(n, (ast.FunctionDef, ast.ClassDef)):
                body = n.body
                if body and isinstance(body[0], ast.Expr) and isinstance(getattr(body[0], "value", None), ast.Constant):
                    n.body = body[1:]
                out.setdefault(n.name, []).append(ast.dump(n))
        return out
    head = defs(_git_head_source())
    now = defs(Path(d3.__file__).read_text())
    assert {k for k in head if now.get(k) != head[k]} == set()
